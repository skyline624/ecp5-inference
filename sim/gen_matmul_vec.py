#!/usr/bin/env python3
# gen_matmul_vec.py -- Gate 3 matmul test vectors (G2: prove in Python first).
#
# Generates int8 W[8][8] and x[8], computes y = W @ x (int32), and emits
# matmul_data.vh (a Verilog initial block) consumed by ecp5/board/matmul_test.v.
# Deterministic (fixed seed) so the hardware's hardcoded expected matches.
#
# Run:  python gen_matmul_vec.py  -> writes ../../build/matmul_data.vh
import sys, os

M, K = 8, 8
# deterministic LCG (no randomness needed, just varied signed values)
def lcg(seed):
    s = seed
    while True:
        s = (1103515245 * s + 12345) & 0x7fffffff
        yield s

g = lcg(0xC0FFEE)
def sint8():
    v = next(g) % 256
    return v - 256 if v >= 128 else v

W = [[sint8() for _ in range(K)] for _ in range(M)]
x = [sint8() for _ in range(K)]
# keep products/sums well within int32 (int8*int8*8 max ~ 8*127*127 ~ 129k)
y = [sum(W[m][k] * x[k] for k in range(K)) for m in range(M)]

# emit Verilog initial block
out = os.path.join(os.path.dirname(__file__), "..", "build", "matmul_data.vh")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as f:
    f.write("// auto-generated by ecp5/sim/gen_matmul_vec.py -- do not edit\n")
    f.write("// W[8][8] (int8), x[8] (int8), expected y[8] = W@x (int32)\n")
    f.write("initial begin\n")
    for m in range(M):
        for k in range(K):
            f.write(f"  W[{m*K+k}] = {W[m][k]:d};\n")
    for k in range(K):
        f.write(f"  x[{k}] = {x[k]:d};\n")
    for m in range(M):
        f.write(f"  expected[{m}] = {y[m]:d};\n")
    f.write("end\n")

print("W @ x =")
for m in range(M):
    print(f"  y[{m}] = {y[m]:>8d}   W[{m}] = {W[m]}")
print(f"\nwrote {out}")